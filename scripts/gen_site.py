#!/usr/bin/env python3
"""Generate site.py from the manifest.

ARKlight discovers routes by reading the entry file's syntax, so every
@site.page(...) decorator must be literally present in site.py. Rather
than hand-maintaining one per route, this script writes them from the
manifest.

Usage: python scripts/gen_site.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pages.manifest import PAGES  # noqa: E402
from theme import FONT_FAMILY, ROLES  # noqa: E402


def fn_name(route):
    if route == "/":
        return "page_home"
    return "page_" + re.sub(r"[^a-z0-9]+", "_", route.lower()).strip("_")


def main():
    lines = [
        "# include <stdlib.ARKlight>",
        f"# GENERATED by scripts/gen_site.py ({len(PAGES)} routes) -- do not edit.",
        "# Edit pages/manifest.py, content/*.py and theme.py instead, then run `make site`.",
        "#",
        "# Every @site.page decorator must live in THIS file: ARKlight finds routes",
        "# by reading this file's syntax, not by running it.",
        "",
        "from components.render import render",
        "from theme import apply_theme",
        "",
        'site = Site(',
        '    name="arklight-site", lang="en", max_width="72rem", sidebar_width="14rem",',
        f'    bg={ROLES["surface"]!r}, font_family={FONT_FAMILY!r}, button_text={ROLES["on-primary"]!r},',
        ")",
        "# Material You (MD3) theme -- see theme.py.",
        "apply_theme(site)",
        "",
    ]
    for p in PAGES:
        lines += [
            "",
            f'@site.page("{p["route"]}")',
            f"def {fn_name(p['route'])}():",
            f'    return render("{p["route"]}")',
        ]
    with open(os.path.join(ROOT, "site.py"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote site.py: {len(PAGES)} routes")


if __name__ == "__main__":
    main()
