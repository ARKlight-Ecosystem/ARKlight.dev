#!/usr/bin/env python3
"""Regenerate docs/CONTENT-STATUS.md from the manifest + content."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from content import CONTENT  # noqa: E402
from pages.manifest import PAGES  # noqa: E402

rows = []
for p in PAGES:
    c = CONTENT[p["route"]]
    status = "DRAFT (outline)" if c.get("draft") else "written"
    rows.append(f"| `{p['route']}` | {p['section']} | {p['phase']} | {status} |")

done = sum(1 for p in PAGES if not CONTENT[p["route"]].get("draft"))
out = [
    "# Content status",
    "",
    "_Generated by `python scripts/status.py`. Do not edit by hand._",
    "",
    f"{done} of {len(PAGES)} pages written; {len(PAGES) - done} are draft outlines.",
    "Drafts render with a visible DRAFT banner and are blocked from release builds",
    "(`make release`, `make pitstop`) by `scripts/check_content.py --release`.",
    "",
    "| Route | Section | Phase | Status |",
    "|---|---|---|---|",
] + rows
open(os.path.join(ROOT, "docs", "CONTENT-STATUS.md"), "w").write("\n".join(out) + "\n")
print(f"wrote docs/CONTENT-STATUS.md ({done}/{len(PAGES)} written)")
